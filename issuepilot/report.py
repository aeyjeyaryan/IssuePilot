"""Reporting: turn the agent state into a human readable markdown report."""

from __future__ import annotations

from typing import Any, Dict, List

from issuepilot.patch import diff_of_files


def _fence(text: str, language: str = "") -> str:
    """Wrap ``text`` in a markdown code fence."""
    return f"```{language}\n{text.rstrip()}\n```"


def build_report(state: Dict[str, Any]) -> str:
    """Build the markdown report for a finished run.

    Args:
        state: The final agent state.

    Returns:
        A markdown document describing the issue, the fix and the test results.
    """
    issue = state.get("issue", {}) or {}
    lines: List[str] = []
    lines.append(f"# IssuePilot report: {issue.get('title', 'unknown issue')}")
    lines.append("")
    lines.append(f"- **Issue**: {issue.get('url', 'n/a')}")
    lines.append(f"- **Repository**: {issue.get('owner', '')}/{issue.get('repo', '')}".rstrip("/"))
    lines.append(f"- **Outcome**: {state.get('outcome', 'unknown')}")
    lines.append(f"- **Attempts**: {state.get('attempts', 0)}")
    if state.get("branch"):
        lines.append(f"- **Branch**: `{state['branch']}`")
    if state.get("pr_url"):
        lines.append(f"- **Pull request**: {state['pr_url']}")
    elif state.get("pr_message"):
        lines.append(f"- **Pull request**: {state['pr_message']}")
    lines.append("")

    if state.get("error"):
        lines.append("## Error")
        lines.append("")
        lines.append(state["error"])
        lines.append("")

    lines.append("## Root cause")
    lines.append("")
    lines.append(state.get("root_cause") or "_The agent did not produce a root cause analysis._")
    lines.append("")

    if state.get("failing_test"):
        lines.append("## Reproduction test")
        lines.append("")
        lines.append(f"`{state.get('failing_test_path', 'tests/test_issue_repro.py')}`")
        lines.append("")
        lines.append(_fence(state["failing_test"], "python"))
        lines.append("")

    if state.get("patch"):
        lines.append("## Fix (unified diff)")
        lines.append("")
        lines.append(_fence(state["patch"], "diff"))
        lines.append("")

    if state.get("files_changed"):
        lines.append("## Files changed")
        lines.append("")
        for path in state["files_changed"]:
            lines.append(f"- `{path}`")
        lines.append("")

    lines.append("## Test results")
    lines.append("")
    summary = state.get("test_summary") or "no summary available"
    lines.append(f"- **Result**: {'PASSED' if state.get('sandbox_ok') else 'FAILED'}")
    lines.append(f"- **Summary**: {summary}")
    lines.append(f"- **Sandbox**: {state.get('sandbox_backend', 'n/a')}")
    output = state.get("sandbox_output", "")
    if output:
        lines.append("")
        lines.append(_fence(output[-4000:]))
    lines.append("")

    relevant = state.get("relevant_chunks", [])
    if relevant:
        lines.append("## Retrieved code")
        lines.append("")
        for item in relevant[:10]:
            lines.append(f"- `{item['file_path']}:{item['start_line']}-{item['end_line']}` — {item.get('type', '')} `{item.get('name', '')}`")
        lines.append("")

    return "\n".join(lines)


def build_pr_body(state: Dict[str, Any]) -> str:
    """Build the body of the pull request."""
    issue = state.get("issue", {}) or {}
    lines: List[str] = []
    lines.append("## Root cause")
    lines.append("")
    lines.append(state.get("root_cause") or "_Not analysed._")
    lines.append("")
    lines.append("## The fix")
    lines.append("")
    if state.get("files_changed"):
        for path in state["files_changed"]:
            lines.append(f"- `{path}`")
    else:
        lines.append("_See the diff below._")
    lines.append("")
    if state.get("patch"):
        lines.append("```diff")
        lines.append(state["patch"].rstrip())
        lines.append("```")
        lines.append("")
    lines.append("## Test results")
    lines.append("")
    lines.append(f"- Result: **{'PASSED' if state.get('sandbox_ok') else 'FAILED'}**")
    if state.get("test_summary"):
        lines.append(f"- Summary: {state['test_summary']}")
    output = state.get("sandbox_output", "")
    if output:
        lines.append("")
        lines.append("```")
        lines.append(output[-2500:].rstrip())
        lines.append("```")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("Generated by [IssuePilot](https://github.com/example/issuepilot), an issue-to-PR agent.")
    return "\n".join(lines)


def working_tree_diff(state: Dict[str, Any]) -> str:
    """Return the diff of the working copy (falls back to the agent patch)."""
    repo_path = state.get("repo_path")
    if repo_path:
        files = state.get("files_changed") or []
        if files:
            diff = diff_of_files(repo_path, files)
            if diff.strip():
                return diff
    return state.get("patch", "")
